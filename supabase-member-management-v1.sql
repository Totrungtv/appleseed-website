-- Apple Seed Member Management V1
-- Trial 3 days + member wallet/coins + payment proof + admin controls.
-- Separate migration: safe to rollback independently.

create table if not exists public.member_accounts (
  user_id uuid primary key references auth.users(id) on delete cascade,
  coins bigint not null default 0 check (coins >= 0),
  status text not null default 'trial'
    check (status in ('trial','active','expired','suspended')),
  trial_started_at timestamptz not null default now(),
  trial_expires_at timestamptz not null default (now() + interval '3 days'),
  last_seen_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists member_accounts_status_idx on public.member_accounts(status);
create index if not exists member_accounts_trial_expires_idx on public.member_accounts(trial_expires_at);

create table if not exists public.member_payment_requests (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  amount_vnd numeric(14,0) not null default 0 check (amount_vnd >= 0),
  requested_coins bigint not null default 0 check (requested_coins >= 0),
  bank_name text not null default 'MB Bank',
  bank_account text not null default '0898888269',
  account_holder text not null default 'Tô Thanh Trung',
  transfer_reference text not null default '',
  proof_path text,
  note text not null default '',
  status text not null default 'pending'
    check (status in ('pending','approved','rejected','cancelled')),
  submitted_at timestamptz not null default now(),
  reviewed_at timestamptz,
  reviewed_by uuid references auth.users(id) on delete set null,
  rejection_reason text not null default ''
);

create index if not exists member_payment_requests_user_idx
  on public.member_payment_requests(user_id, submitted_at desc);
create index if not exists member_payment_requests_status_idx
  on public.member_payment_requests(status, submitted_at desc);

create table if not exists public.member_coin_ledger (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  delta bigint not null,
  balance_after bigint not null,
  transaction_type text not null
    check (transaction_type in ('admin_credit','admin_debit','payment_credit','usage','adjustment')),
  payment_request_id uuid references public.member_payment_requests(id) on delete set null,
  note text not null default '',
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create index if not exists member_coin_ledger_user_idx
  on public.member_coin_ledger(user_id, created_at desc);

create or replace function public.apple_seed_create_member_account()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.member_accounts(user_id, trial_started_at, trial_expires_at)
  values (new.id, coalesce(new.created_at, now()), coalesce(new.created_at, now()) + interval '3 days')
  on conflict (user_id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_member_account on auth.users;
create trigger on_auth_user_created_member_account
after insert on auth.users
for each row execute function public.apple_seed_create_member_account();

insert into public.member_accounts(user_id, trial_started_at, trial_expires_at, created_at, updated_at)
select u.id, u.created_at, u.created_at + interval '3 days', coalesce(u.created_at,now()), now()
from auth.users u
on conflict (user_id) do nothing;

