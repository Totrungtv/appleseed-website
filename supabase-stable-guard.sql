create table if not exists public.stable_guard_snapshots (
  id bigint generated by default as identity primary key,
  repository text not null default 'Totrungtv/appleseed-website',
  branch text not null default 'main',
  commit_sha text not null,
  label text not null default 'Stable',
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  metadata jsonb not null default '{}'::jsonb,
  unique(repository, branch, commit_sha)
);

create index if not exists stable_guard_snapshots_created_at_idx
  on public.stable_guard_snapshots(created_at desc);

create table if not exists public.stable_guard_requests (
  id uuid primary key default gen_random_uuid(),
  snapshot_id bigint not null references public.stable_guard_snapshots(id) on delete restrict,
  requested_by uuid references auth.users(id) on delete set null,
  status text not null default 'pending'
    check (status in ('pending','processing','succeeded','failed','cancelled')),
  requested_at timestamptz not null default now(),
  processed_at timestamptz,
  result_commit_sha text,
  message text not null default '',
  error_message text not null default ''
);

create index if not exists stable_guard_requests_status_idx
  on public.stable_guard_requests(status, requested_at);

alter table public.stable_guard_snapshots enable row level security;
alter table public.stable_guard_requests enable row level security;

