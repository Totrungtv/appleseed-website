create or replace function public.stable_guard_claim_request(p_worker text default 'github-actions')
returns table (request_id uuid, snapshot_id bigint, repository text, branch text, commit_sha text, label text)
language plpgsql security definer set search_path = public
as $$
begin
  return query
  with picked as (
    select r.id from public.stable_guard_requests r
    where r.status = 'pending'
    order by r.requested_at asc
    for update skip locked limit 1
  ),
  claimed as (
    update public.stable_guard_requests r
    set status = 'processing',
        message = case when r.message = '' then 'Claimed by ' || coalesce(p_worker,'worker') else r.message end
    from picked where r.id = picked.id
    returning r.id, r.snapshot_id
  )
  select c.id, s.id, s.repository, s.branch, s.commit_sha, s.label
  from claimed c join public.stable_guard_snapshots s on s.id = c.snapshot_id;
end;
$$;

create or replace function public.stable_guard_complete_request(
  p_request_id uuid, p_status text, p_result_commit_sha text default null,
  p_message text default '', p_error_message text default ''
)
returns boolean
language plpgsql security definer set search_path = public
as $$
begin
  if p_status not in ('succeeded','failed','cancelled') then raise exception 'Invalid stable guard status'; end if;
  update public.stable_guard_requests
  set status=p_status, processed_at=now(), result_commit_sha=p_result_commit_sha,
      message=coalesce(p_message,''), error_message=coalesce(p_error_message,'')
  where id=p_request_id and status='processing';
  return found;
end;
$$;

grant execute on function public.stable_guard_claim_request(text) to anon, authenticated;
grant execute on function public.stable_guard_complete_request(uuid,text,text,text,text) to anon, authenticated;


